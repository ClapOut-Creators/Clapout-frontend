// Runs automatically before `npm run build` (npm "prebuild" hook).
// Bakes deploy-time environment variables into the bundle by regenerating
// src/app/core/config/runtime-env.ts. On Vercel, set API_BASE_URL in the
// project's Environment Variables; locally the default keeps dev working.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const apiBaseUrl = process.env.API_BASE_URL?.trim() || 'http://localhost:4000/api/v1';

if (!/^https?:\/\/[^'"\\\s]+$/.test(apiBaseUrl)) {
  console.error(`API_BASE_URL must be an absolute http(s) URL, got: ${apiBaseUrl}`);
  process.exit(1);
}

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src/app/core/config/runtime-env.ts',
);

writeFileSync(
  target,
  `// GENERATED by scripts/generate-runtime-env.mjs before every build — do not
// edit by hand and do not import anywhere except app.config.ts. The committed
// version carries the local-dev default.
export const RUNTIME_API_BASE_URL = '${apiBaseUrl}';
`,
);

console.log(`[runtime-env] apiBaseUrl = ${apiBaseUrl}`);
